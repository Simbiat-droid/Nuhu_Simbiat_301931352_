#!/usr/bin/env bash
# Portfolio 2 - Query Processing and Optimisation runner.
# Student: Nuhu Simbiat - 2026/A/MIT/0955
# Database: readwell (PostgreSQL 16, created by Portfolio 1)
#
# Runs the analytical queries, EXPLAIN ANALYZE BEFORE indexing (a true
# baseline: the helper indexes are dropped first), creates the indexes, runs
# EXPLAIN ANALYZE AFTER, and writes p2_timing_summary.md from the REAL
# "Execution Time" lines, so nothing has to be copied by hand.
set -euo pipefail
DB=readwell
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PSQL=(sudo runuser -u postgres -- psql -X -v ON_ERROR_STOP=1 -d "$DB")
run_sql() { echo; echo "== $2 =="; "${PSQL[@]}" -f - < "$DIR/$1"; }

N=$("${PSQL[@]}" -At -c "SELECT count(*) FROM loan")
if [ "$N" -lt 50000 ]; then echo "Run Portfolio 1 first: only $N loans."; exit 1; fi

run_sql 01_queries.sql        "Running analytical queries Q1-Q8"
run_sql 02_explain_before.sql "EXPLAIN ANALYZE BEFORE indexes" | tee "$DIR/explain_before.txt"
run_sql 03_indexes.sql        "Creating indexes"
run_sql 04_explain_after.sql  "EXPLAIN ANALYZE AFTER indexes"  | tee "$DIR/explain_after.txt"

summ() {  # $1 file -> "Qn|scan on loan (or first scan)|exec ms" lines
  awk 'function nodeof(x){ sub(/^.*->  /,"",x); sub(/^ +/,"",x); sub(/  \(.*$/,"",x); return x }
       /--- Q[0-9]+ EXPLAIN/ {q=$2; L=""; O=""; next}
       q!="" && /(Seq Scan|Index Scan|Index Only Scan|Bitmap Heap Scan)( using [a-z_0-9]+)? on loan[_a-z0-9]* / && L=="" {L=nodeof($0)}
       q!="" && /(Seq Scan|Index Scan|Index Only Scan|Bitmap Heap Scan)( using [a-z_0-9]+)? on (copy|book|fine|reservation) / && O=="" {O=nodeof($0)}
       q!="" && /Execution Time/ {print q "|" (L!="" ? L : O) "|" $3; q=""}' "$1"
}
summ "$DIR/explain_before.txt" > /tmp/p2_before.$$
summ "$DIR/explain_after.txt"  > /tmp/p2_after.$$
{
  echo "# Portfolio 2 - real timings from this run ($(date '+%Y-%m-%d %H:%M'))"
  echo
  echo "| Query | Before: scan on loan | Before (ms) | After: scan on loan | After (ms) | Speed-up |"
  echo "|---|---|---|---|---|---|"
  paste -d'|' /tmp/p2_before.$$ /tmp/p2_after.$$ | \
    awk -F'|' '{sp = ($6>0) ? sprintf("%.1fx", $3/$6) : "-"; printf "| %s | %s | %s | %s | %s | %s |\n", $1,$2,$3,$5,$6,sp}'
  echo
  echo "Generated by run_p2.sh from explain_before.txt / explain_after.txt."
  echo "Q1-Q6 aggregate most of the loan table, so a Seq Scan stays the cheapest plan"
  echo "and small differences are run-to-run noise; Q9/Q10 are selective lookups."
} | tee "$DIR/p2_timing_summary.md"
rm -f /tmp/p2_before.$$ /tmp/p2_after.$$
echo "== Portfolio 2 complete =="
